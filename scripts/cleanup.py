#!/usr/bin/env python3
"""Cleanup script for biocurate repository.

Removes:
- Duplicate copy-paste files generated by OS / sync tools (e.g. '* 2.py', '* (1).ts', '* copy.*')
- Redundant nested directories (e.g. 'frontend/frontend')
- OS metadata files (e.g. '.DS_Store', '._*')
- Untracks removed files from git if tracked.

Usage:
    python scripts/cleanup.py --dry-run
    python scripts/cleanup.py
    python scripts/cleanup.py --caches  # also clean __pycache__, .pytest_cache, etc.
"""

from __future__ import annotations

import argparse
import os
import re
import shutil
import subprocess
from pathlib import Path

# Match duplicate copy patterns, e.g.:
# "file 2.py", "file 2", "file (1).tsx", "file copy.json"
DUPLICATE_FILE_RE = re.compile(
    r"""
    .*                # Prefix
    (
        \s+\d+(\.[^.]+)?$        # e.g. " 2.py" or " 2"
      | \s+\(\d+\)(\.[^.]+)?$    # e.g. " (1).ts" or " (1)"
      | \s+copy(\.[^.]+)?$       # e.g. " copy.md" or " copy"
    )
    """,
    re.VERBOSE | re.IGNORECASE,
)

OS_JUNK_NAMES = {".DS_Store", "Thumbs.db", "ehthumbs.db"}

CACHE_DIRS = {"__pycache__", ".pytest_cache", ".ruff_cache", ".mypy_cache"}


def is_os_junk(name: str) -> bool:
    return name in OS_JUNK_NAMES or name.startswith("._")


def is_duplicate_artifact(path: Path) -> bool:
    name = path.name
    # Don't match root or system directories
    if name in {".", ".."}:
        return False
    return bool(DUPLICATE_FILE_RE.match(name))


def find_redundant_dirs(root: Path) -> list[Path]:
    redundant: list[Path] = []
    # e.g. frontend/frontend
    nested_frontend = root / "frontend" / "frontend"
    if nested_frontend.is_dir():
        redundant.append(nested_frontend)
    return redundant


def get_git_tracked_files(root: Path) -> set[str]:
    try:
        res = subprocess.run(
            ["git", "-C", str(root), "ls-files"],
            capture_output=True,
            text=True,
            check=True,
        )
        return set(res.stdout.splitlines())
    except (subprocess.SubprocessError, FileNotFoundError):
        return set()


def main() -> None:
    parser = argparse.ArgumentParser(description="Clean up repository duplicate and unnecessary files.")
    parser.add_argument("--dry-run", action="store_true", help="Print files that would be removed without deleting.")
    parser.add_argument("--caches", action="store_true", help="Also remove __pycache__ and tool cache directories.")
    args = parser.parse_args()

    repo_root = Path(__file__).resolve().parent.parent

    files_to_remove: list[Path] = []
    dirs_to_remove: list[Path] = find_redundant_dirs(repo_root)

    ignored_parents = {repo_root / ".git", repo_root / ".venv", repo_root / "node_modules", repo_root / "frontend" / "node_modules"}

    for current_dir, dirnames, filenames in os.walk(repo_root):
        curr_path = Path(current_dir)
        if any(ignored in curr_path.parents or curr_path == ignored for ignored in ignored_parents):
            continue

        if args.caches:
            for d in list(dirnames):
                if d in CACHE_DIRS:
                    dirs_to_remove.append(curr_path / d)
                    dirnames.remove(d)

        for f in filenames:
            file_path = curr_path / f
            if is_os_junk(f) or is_duplicate_artifact(file_path):
                files_to_remove.append(file_path)

    tracked_files = get_git_tracked_files(repo_root)

    total_items = len(files_to_remove) + len(dirs_to_remove)
    print("=== Biocurate Repository Cleanup ===")
    print(f"Target directory: {repo_root}")
    print(f"Found {len(files_to_remove)} unnecessary files and {len(dirs_to_remove)} directories.")

    if total_items == 0:
        print("Everything is clean! No unnecessary files found.")
        return

    tracked_to_git_rm: list[str] = []

    for d in dirs_to_remove:
        rel_path = str(d.relative_to(repo_root))
        print(f"  [DIR]  {rel_path}")
        # Check if any tracked files exist under this directory
        for tf in tracked_files:
            if tf.startswith(rel_path + "/") or tf == rel_path:
                tracked_to_git_rm.append(tf)

    for f in files_to_remove:
        rel_path = str(f.relative_to(repo_root))
        print(f"  [FILE] {rel_path}")
        if rel_path in tracked_files:
            tracked_to_git_rm.append(rel_path)

    if args.dry_run:
        print(f"\n[DRY RUN] Would delete {total_items} items ({len(tracked_to_git_rm)} currently tracked in git).")
        return

    # If items are tracked in git, remove them via git rm
    if tracked_to_git_rm:
        print(f"\nUntracking {len(tracked_to_git_rm)} items from git...")
        try:
            # Batch git rm calls
            subprocess.run(
                ["git", "-C", str(repo_root), "rm", "-f", "--ignore-unmatch", *tracked_to_git_rm],
                check=True,
            )
            print("Successfully untracked git files.")
        except subprocess.SubprocessError as e:
            print(f"Warning: git rm failed ({e}), will proceed with filesystem deletion.")

    # Remove files from filesystem if they still exist
    deleted_files = 0
    for f in files_to_remove:
        if f.exists() or f.is_symlink():
            try:
                f.unlink()
                deleted_files += 1
            except OSError as e:
                print(f"Error removing file {f}: {e}")

    # Remove directories
    deleted_dirs = 0
    for d in dirs_to_remove:
        if d.exists() and d.is_dir():
            try:
                shutil.rmtree(d)
                deleted_dirs += 1
            except OSError as e:
                print(f"Error removing directory {d}: {e}")

    print(f"\nCleanup complete: removed {deleted_files} files and {deleted_dirs} directories.")


if __name__ == "__main__":
    main()
